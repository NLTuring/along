// Builds mobile/assets/js/seed-places.js from the product seed data, so place
// names, hours, prices and the plan template are copied rather than retyped.
// Usage: node mobile/tools/build-seed.mjs
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const at = (p) => fileURLToPath(new URL(p, import.meta.url));
const seed = JSON.parse(await readFile(at('../../一起游-网站分享包-Windows/docs/03-种子数据.json'), 'utf8'));
const credits = JSON.parse(await readFile(at('../assets/img/credits.json'), 'utf8'));

// The seed file points Shanghai places at Nanjing photos as stand-ins. A photo is
// only used here when it really shows the place; credits.json records where each came from.
const PHOTOS = {
  poi_njmuseum: 'nanjing-museum-02.jpg',
  poi_laomendong: 'laomendong.jpg',
  poi_fuzimiao: 'fuzimiao.jpg',
  poi_zhongshan: 'zhongshan-02.jpg',
  poi_jiming: 'jiming.jpg',
  poi_yuyuan: 'yuyuan.jpg',
  poi_westbund: 'westbund.jpg',
  poi_wukang: 'wukang.jpg',
  poi_jingan: 'jingan.jpg',
  poi_ferry: 'ferry.jpg',
  poi_shmuseum: 'shmuseum.jpg',
  poi_zhonghua: 'zhonghua.jpg',
};

const creditByFile = {};
for (const entry of Object.values(credits)) {
  if (!entry || typeof entry !== 'object') continue;
  for (const item of [entry, ...(entry.photoGallery || [])]) {
    if (item.photoUrl) creditByFile[item.photoUrl.replace(/^places\//, '')] = item.photoCredit || '';
  }
}

const pois = {};
for (const p of seed.pois) {
  const file = PHOTOS[p.id] || null;
  pois[p.id] = {
    id: p.id,
    citySlug: p.citySlug,
    nameEn: p.nameEn,
    nameZh: p.nameZh,
    category: p.category,
    lat: p.lat,
    lng: p.lng,
    hours: p.hours,
    priceCents: p.priceCents,
    durationMin: p.durationMin,
    descriptionEn: p.descriptionEn,
    photo: file ? `img/places/${file}` : null,
    photoCredit: file ? creditByFile[file] || '' : '',
  };
}

// Guide fields that the list page does not hand-copy: taken straight from the seed file.
const guideExtra = {};
for (const g of seed.guides) {
  guideExtra[g.id] = {
    bio: g.bio,
    languages: g.languages,
    status: g.status,
    instantBook: g.instantBook,
    priceFullCents: g.priceFullCents,
    slotRule: g.slotRule,
  };
}

const template = seed.planTemplates[0];
const out = `// Generated by mobile/tools/build-seed.mjs from docs/03-种子数据.json. Do not edit by hand.
export const POIS = ${JSON.stringify(pois, null, 2)};

export const PLAN_TEMPLATE = ${JSON.stringify(template, null, 2)};

export const GUIDE_EXTRA = ${JSON.stringify(guideExtra, null, 2)};

export const FILM_STYLES = ${JSON.stringify(seed.filmStyles, null, 2)};

export const SHARE_CAPTION = ${JSON.stringify(seed.copy['share.caption'].replace(/InsTrip/g, 'Along'))};
`;
await writeFile(at('../assets/js/seed-places.js'), out, 'utf8');
console.log(`seed-places.js: ${Object.keys(pois).length} places, ${template.daysData.length} template days, ${Object.values(pois).filter((p) => p.photo).length} with photos`);
