// Generates server/src/assistant-catalog.ts from the mobile seed data, so the assistant can only
// recommend places and local friends that the app can actually open. Usage: node mobile/tools/build-assistant-catalog.mjs [--check]
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { POIS } from '../assets/js/seed-places.js';
import { GUIDES } from '../assets/js/seed.js';

const target = fileURLToPath(new URL('../../server/src/assistant-catalog.ts', import.meta.url));
const places = Object.values(POIS).map((p) => ({
  id: p.id, city: p.citySlug, category: p.category, nameZh: p.nameZh, nameEn: p.nameEn,
  hours: Object.entries(p.hours || {}).map(([days, time]) => `${days.replace('_', '-')} ${time}`).join(', '), priceYuan: Math.round((p.priceCents || 0) / 100), durationMin: p.durationMin || 0, note: p.descriptionEn || '',
}));
const guides = GUIDES.map((g) => ({
  id: g.id, name: g.name, city: g.citySlug, kind: g.kind, headline: g.headline, topics: [...g.topics], halfDayUsd: Math.round((g.priceHalfCents || 0) / 100),
}));
const source = `// Generated by mobile/tools/build-assistant-catalog.mjs from the mobile seed data. Do not edit by hand.
export const ASSISTANT_PLACES = ${JSON.stringify(places, null, 2)} as const;
export const ASSISTANT_GUIDES = ${JSON.stringify(guides, null, 2)} as const;
`;
if (process.argv.includes('--check')) {
  const current = await readFile(target, 'utf8').catch(() => '');
  if (current !== source) { console.error('assistant-catalog.ts is out of date: run node mobile/tools/build-assistant-catalog.mjs'); process.exit(1); }
  console.log('assistant catalog up to date');
} else {
  await writeFile(target, source);
  console.log(`wrote ${places.length} places and ${guides.length} guides`);
}
