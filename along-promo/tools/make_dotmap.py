"""Dot world map for S01 from Natural Earth 110m (public domain, via world-atlas@2).
Equirectangular, centred on 140°E so Europe sits left and the Americas right of Shanghai.
Writes src/scenes/S01/dotmap.ts: LAND / CHINA path strings (one circle per dot) + city positions."""
import json
from pathlib import Path
import numpy as np
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
LON0, S, CX, CY = 140.0, 5.2, 960.0, 470.0  # centre longitude, px per degree, screen position of (LON0, 0°)
STEP, R = 1.55, 1.75  # dot spacing in degrees, dot radius in px
MW, MH = 1440, 720  # mask: 0.25° per pixel


def decode(topo):
    sx, sy = topo["transform"]["scale"]; tx, ty = topo["transform"]["translate"]
    arcs = []
    for arc in topo["arcs"]:
        x = y = 0; pts = []
        for dx, dy in arc:
            x += dx; y += dy; pts.append((x * sx + tx, y * sy + ty))
        arcs.append(pts)
    def ring(idx):
        out = []
        for i in idx:
            a = arcs[i] if i >= 0 else arcs[~i][::-1]
            out.extend(a[1:] if out else a)
        return out
    return ring


def polys(geom):
    t = geom["type"]
    if t == "Polygon": return [geom["arcs"]]
    if t == "MultiPolygon": return geom["arcs"]
    if t == "GeometryCollection": return [p for g in geom["geometries"] for p in polys(g)]
    return []


def mask_of(topo, geoms):
    ring = decode(topo)
    img = Image.new("L", (MW, MH), 0); d = ImageDraw.Draw(img)
    for g in geoms:
        for poly in polys(g):
            for k, r in enumerate(poly):
                pts = [((lon + 180) / 360 * MW, (90 - lat) / 180 * MH) for lon, lat in ring(r)]
                if len(pts) > 2: d.polygon(pts, fill=255 if k == 0 else 0)
    return np.array(img) > 0


land_topo = json.loads(Path(r"D:\along-tmp\land-110m.json").read_text())
land = mask_of(land_topo, [land_topo["objects"]["land"]])
ctry = json.loads(Path(r"D:\along-tmp\countries-110m.json").read_text())
china = mask_of(ctry, [g for g in ctry["objects"]["countries"]["geometries"] if str(g.get("id")) == "156" or g.get("properties", {}).get("name") == "China"])


def project(lon, lat):
    dl = ((lon - LON0 + 540) % 360) - 180
    return CX + dl * S, CY - lat * S


def circle(x, y):
    return f"M{x - R:.1f} {y:.1f}a{R} {R} 0 1 0 {2 * R} 0a{R} {R} 0 1 0 {-2 * R} 0"


land_d, china_d, n = [], [], 0
for lat in np.arange(78, -58, -STEP):
    for dl in np.arange(-180 + STEP / 2, 180, STEP):
        lon = ((LON0 + dl + 180) % 360) - 180
        mx = int((lon + 180) / 360 * MW) % MW; my = int((90 - lat) / 180 * MH)
        if not (0 <= my < MH) or not land[my, mx]: continue
        x, y = project(lon, lat)
        (china_d if china[my, mx] else land_d).append(circle(x, y)); n += 1

CITIES = {"shanghai": (121.47, 31.23), "seoul": (126.98, 37.57), "tokyo": (139.69, 35.69), "newyork": (-74.0, 40.71),
          "losangeles": (-118.24, 34.05), "london": (-0.13, 51.51), "paris": (2.35, 48.86), "frankfurt": (8.68, 50.11),
          "nanjing": (118.8, 32.06)}
pos = {k: [round(v, 1) for v in project(*ll)] for k, ll in CITIES.items()}
out = ROOT / "src" / "scenes" / "S01" / "dotmap.ts"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(
    "// Generated by tools/make_dotmap.py from Natural Earth 110m (public domain). Do not edit.\n"
    f"export const MAP = {{ lon0: {LON0}, scale: {S}, cx: {CX}, cy: {CY}, dot: {R} }};\n"
    f"export const CITY: Record<string, [number, number]> = {json.dumps(pos)};\n"
    f"export const LAND = '{''.join(land_d)}';\n"
    f"export const CHINA = '{''.join(china_d)}';\n", encoding="utf8")
print(n, "dots;", len(china_d), "in China;", out.stat().st_size // 1024, "KB;", pos)
