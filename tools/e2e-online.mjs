async function call(client, path, { method = 'GET', body, form, expected = 200 } = {}) {
  const headers = { Origin: origin };
  if (client?.cookie) headers.Cookie = client.cookie;
  if (client?.csrf && method !== 'GET') headers['X-CSRF-Token'] = client.csrf;
  if (body !== undefined) headers['Content-Type'] = 'application/json';
  const response = await fetch(`${origin}/api${path}`, { method, headers, body: form || (body === undefined ? undefined : JSON.stringify(body)) });
  const cookies = response.headers.getSetCookie();
  if (client && cookies.length) client.cookie = cookies.map((cookie) => cookie.split(';')[0]).join('; ');
  let result;
  if ((response.headers.get('content-type') || '').includes('json')) result = await response.json();
  else result = new Uint8Array(await response.arrayBuffer());
  assert.equal(response.status, expected, `${method} ${path}: ${JSON.stringify(result)}`);
  if (client && result.csrfToken) client.csrf = result.csrfToken;
  assertions++;
  return result;
}
async function login(email) {
  const client = {};
  const otp = await call(client, '/auth/otp', { method: 'POST', body: { email } });
  check(otp.ok && /^\d{6}$/.test(otp.code), 'local mode must explicitly supply development code');
  const verified = await call(client, '/auth/verify', { method: 'POST', body: { email, code: otp.code } });
  check(verified.ok && verified.user.id, 'server verified user');
  client.user = verified.user;
  clients.set(email, client);
  return client;
}
